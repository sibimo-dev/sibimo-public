export function getLetterServiceBySlug(slug) {
  return LETTER_SERVICES.find((service) => service.slug === slug) ?? null;
}

export function getRequiredDocuments(slug) {
  const service = getLetterServiceBySlug(slug);
  return service?.requiredDocuments ?? DEFAULT_REQUIRED_DOCUMENTS;
}

export function getCategoryLabel(value) {
  return LETTER_CATEGORIES.find((category) => category.value === value)?.label ?? value;
}